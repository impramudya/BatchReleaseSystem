<?php

namespace App\Notifications;

use App\Models\Batch;
use Illuminate\Bus\Queueable;
use Illuminate\Notifications\Messages\MailMessage;
use Illuminate\Notifications\Notification;

class BatchStatusNotification extends Notification
{
    use Queueable;

    /**
     * @param Batch $batch
     * @param string $title
     * @param string $message
     * @param string $url
     */
    public function __construct(
        public Batch $batch,
        public string $title,
        public string $message,
        public string $url,
    ) {
    }

    public function via($notifiable): array
    {
        return !empty($notifiable->email)
            ? ['database', 'mail']
            : ['database'];
    }

    public function toMail($notifiable): MailMessage
    {
        $batch = $this->batch;
        $batchNumber = $batch->batch_number;
        $productName = $batch->product->name ?? '-';
        $productCode = $batch->product->product_code ?? '-';
        $lineName = $batch->productionLine->name ?? '-';
        $batchDate = $batch->batch_date?->format('d M Y') ?? '-';
        $creatorName = $batch->creator_display_name;

        return (new MailMessage)
            ->subject($this->title)
            ->greeting('Hello ' . $notifiable->name . ',')
            ->line($this->message)
            ->line('**Batch Information:**')
            ->line('• **Batch Number:** ' . $batchNumber)
            ->line('• **Product:** ' . $productName . ' (' . $productCode . ')')
            ->line('• **Production Line:** ' . $lineName)
            ->line('• **Batch Date:** ' . $batchDate)
            ->line('• **Submitted By:** ' . $creatorName)
            ->action('Open Task Approval System', $this->url)
            ->line('Please review and process this task by clicking the button above.')
            ->line('This email is automatically generated by the Batch Release System.')
            ->salutation("Regards,\nPT. Saka Farma Laboratories (Kalbe Consumer Health)");
    }

    public function toArray($notifiable): array
    {
        return [
            'batch_id' => $this->batch->id,
            'title' => $this->title,
            'message' => $this->message,
            'url' => $this->url,
        ];
    }
}
